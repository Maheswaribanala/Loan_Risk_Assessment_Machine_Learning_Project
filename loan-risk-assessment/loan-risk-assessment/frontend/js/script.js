/* script.js — shared helpers used across all pages */

const API_BASE = ""; // same-origin (Flask serves both frontend + API)

/** Injects the shared navbar into an element with id="lra-nav" and marks
 *  the current page active. */
function renderNavbar(active) {
  const el = document.getElementById("lra-nav");
  if (!el) return;
  const links = [
    { href: "index.html", label: "Home", key: "home" },
    { href: "assessment.html", label: "Assess Loan Risk", key: "assessment" },
    { href: "dashboard.html", label: "Dashboard", key: "dashboard" },
  ];
  el.innerHTML = `
    <nav class="navbar navbar-expand-md lra-navbar py-3">
      <div class="container">
        <a class="navbar-brand" href="index.html">
          <span class="mark">₹</span>
          Intelligent Loan Risk Assessment
        </a>
        <button class="navbar-toggler border-0 text-white" type="button" data-bs-toggle="collapse" data-bs-target="#lraNavCollapse">
          <span class="navbar-toggler-icon"></span>
        </button>
        <div class="collapse navbar-collapse justify-content-end" id="lraNavCollapse">
          <ul class="navbar-nav">
            ${links.map(l => `
              <li class="nav-item">
                <a class="nav-link ${l.key === active ? "active" : ""}" href="${l.href}">${l.label}</a>
              </li>`).join("")}
          </ul>
        </div>
      </div>
    </nav>
  `;
}

